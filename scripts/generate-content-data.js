"use strict";

const fs = require("fs");
const path = require("path");

const rootDir = path.join(__dirname, "..");
const contentDir = path.join(rootDir, "content");
const outputPath = path.join(rootDir, "lib", "content-data.generated.ts");

function collectFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...collectFiles(fullPath));
    else if (entry.isFile() && /\.(json|md)$/.test(entry.name)) files.push(fullPath);
  }
  return files;
}

const embedded = Object.fromEntries(
  collectFiles(contentDir).map((filePath) => [
    path.relative(rootDir, filePath).split(path.sep).join("/"),
    fs.readFileSync(filePath, "utf8"),
  ])
);

const source = `// Generated by scripts/generate-content-data.js. Do not edit.\n` +
  `export const EMBEDDED_CONTENT: Record<string, string> = ${JSON.stringify(embedded, null, 2)};\n`;

fs.writeFileSync(outputPath, source, "utf8");
console.log(`Embedded ${Object.keys(embedded).length} content files in ${path.relative(rootDir, outputPath)}`);
