"use strict";

/**
 * Build-time content catalog.
 *
 * Always run before Next compiles. next.config.ts, npm prebuild/predev/prevalidate,
 * and OpenNext buildCommand all call this so published-lesson slugs cannot go stale.
 */

const fs = require("fs");
const path = require("path");

function defaultRoot() {
  return path.join(__dirname, "..");
}

function collectFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...collectFiles(fullPath));
    else if (entry.isFile() && /\.(json|md)$/.test(entry.name)) files.push(fullPath);
  }
  return files;
}

function isPublicLessonMarkdown(body) {
  if (/\nenabled:\s*false\b/.test(body) || /^enabled:\s*false\b/m.test(body)) return false;
  const status = /(?:^|\n)status:\s*["']?([A-Za-z-]+)/.exec(body);
  if (!status) return true;
  const value = status[1].toLowerCase();
  return value !== "draft" && value !== "archived";
}

function collectPublishedLessonSlugs(embedded) {
  return [
    ...new Set(
      Object.entries(embedded)
        .filter(([filePath, body]) => {
          if (!filePath.endsWith(".md")) return false;
          if (!filePath.startsWith("content/lessons/") && !filePath.startsWith("content/courses/")) {
            return false;
          }
          return isPublicLessonMarkdown(String(body));
        })
        .map(([filePath]) => path.basename(filePath, ".md"))
    ),
  ].sort();
}

function collectStaticLearnSegments(rootDir) {
  const learnDir = path.join(rootDir, "app", "learn");
  if (!fs.existsSync(learnDir)) return [];
  return fs
    .readdirSync(learnDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("[") && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort();
}

function writeIfChanged(filePath, contents) {
  try {
    if (fs.existsSync(filePath) && fs.readFileSync(filePath, "utf8") === contents) {
      return false;
    }
  } catch {
    // fall through and write
  }
  fs.writeFileSync(filePath, contents, "utf8");
  return true;
}

function generateContentData(rootDir) {
  const root = rootDir || defaultRoot();
  const contentDir = path.join(root, "content");
  const outputPath = path.join(root, "lib", "content-data.generated.ts");

  const embedded = Object.fromEntries(
    collectFiles(contentDir).map((filePath) => [
      path.relative(root, filePath).split(path.sep).join("/"),
      fs.readFileSync(filePath, "utf8"),
    ])
  );

  const source =
    `// Generated by scripts/generate-content-data.js. Do not edit.\n` +
    `export const EMBEDDED_CONTENT: Record<string, string> = ${JSON.stringify(embedded, null, 2)};\n`;

  const catalogChanged = writeIfChanged(outputPath, source);
  console.log(
    `${catalogChanged ? "Embedded" : "Catalog unchanged,"} ${Object.keys(embedded).length} content files in ${path.relative(root, outputPath)}`
  );

  const lessonSlugs = collectPublishedLessonSlugs(embedded);
  const staticLearn = collectStaticLearnSegments(root);
  const slugSource =
    "// Generated by scripts/generate-content-data.js. Do not edit.\n" +
    "export const PUBLISHED_LESSON_SLUGS = " +
    JSON.stringify(lessonSlugs) +
    " as const;\n" +
    "export const PUBLISHED_LESSON_SLUG_SET = new Set<string>(PUBLISHED_LESSON_SLUGS);\n" +
    "export const STATIC_LEARN_SEGMENTS = " +
    JSON.stringify(staticLearn) +
    " as const;\n" +
    "export const STATIC_LEARN_SEGMENT_SET = new Set<string>(STATIC_LEARN_SEGMENTS);\n";

  const slugPath = path.join(root, "lib", "published-lesson-slugs.generated.ts");
  const slugsChanged = writeIfChanged(slugPath, slugSource);
  console.log(
    `${slugsChanged ? "Wrote" : "Slug catalog unchanged,"} published lesson slugs (${lessonSlugs.length}) and static /learn segments (${staticLearn.join(", ") || "none"}) in ${path.relative(root, slugPath)}`
  );

  return { embedded, lessonSlugs, staticLearn, outputPath, slugPath };
}

if (require.main === module) {
  generateContentData();
}

module.exports = {
  generateContentData,
  collectPublishedLessonSlugs,
  collectStaticLearnSegments,
  isPublicLessonMarkdown,
  writeIfChanged,
};
